  /**
   * Fast lookup by language ID (BCP 47).
   * Safe fallback to Spanish or English if unknown.
   */
  fun getLanguageById(id: String): Language {
    return allLanguages.find { it.id.equals(id, ignoreCase = true) }
      ?: allLanguages.firstOrNull { it.id == "es" }
      ?: allLanguages.first()
  }

  /**
   * Filter languages by query (name, nativeName, region, ID) and region tab.
   */
  fun filterLanguages(query: String, regionFilter: String): List<Language> {
    val cleanQuery = query.trim().lowercase()
    return allLanguages.filter { lang ->
      val matchesRegion = when (regionFilter) {
        "All" -> true
        "Popular" -> lang.isPopular
        "Europe" -> lang.region.contains("Europe", ignoreCase = true)
        "Asia" -> lang.region.contains("Asia", ignoreCase = true)
        "Americas" -> lang.region.contains("Americas", ignoreCase = true)
        "Africa & Middle East", "Africa" -> lang.region.contains("Africa", ignoreCase = true) || lang.region.contains("Middle East", ignoreCase = true)
        "Oceania" -> lang.region.contains("Oceania", ignoreCase = true)
        else -> true
      }
      val matchesQuery = cleanQuery.isEmpty() ||
        lang.name.lowercase().contains(cleanQuery) ||
        lang.nativeName.lowercase().contains(cleanQuery) ||
        lang.region.lowercase().contains(cleanQuery) ||
        lang.id.lowercase() == cleanQuery
      matchesRegion && matchesQuery
    }
  }

  /**
   * Curated list of popular entry languages for quick start.
   */
  fun getPopularLanguages(): List<Language> = allLanguages.filter { it.isPopular }
